"""llmdiff integrations: CI platforms, chat apps, paging and metrics.

This package wires verdict results into the systems teams already use:

- :mod:`llmdiff.integrations.github_app` — GitHub App webhooks, PR comments,
  commit statuses,
- :mod:`llmdiff.integrations.gitlab` — GitLab webhooks, MR notes, statuses,
- :mod:`llmdiff.integrations.jenkins` — build triggers, console logs, gates,
- :mod:`llmdiff.integrations.slack_app` — Events API, slash commands, Block Kit,
- :mod:`llmdiff.integrations.discord_app` — interactions, embeds, webhooks,
- :mod:`llmdiff.integrations.teams` — Adaptive Cards, incoming webhooks,
- :mod:`llmdiff.integrations.webhook` — generic signed outbound webhooks with
  retries and a SQLite delivery log,
- :mod:`llmdiff.integrations.pagerduty` — Events API v2 incidents,
- :mod:`llmdiff.integrations.opsgenie` — Alerts API v2,
- :mod:`llmdiff.integrations.datadog` — metrics + events,
- :mod:`llmdiff.integrations.prometheus` — ``/metrics`` text exposition,
- :mod:`llmdiff.integrations.linear_app` — Linear GraphQL issues/comments,
- :mod:`llmdiff.integrations.jira_app` — Jira REST v3 issues/comments.

All HTTP is injectable, so every integration is testable offline.
"""

